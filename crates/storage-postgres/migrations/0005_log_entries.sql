-- One log entry holds what a person logged once (who, when, which event, the note) and owns
-- an optional smell report and an optional PM2.5 reading (design: log entries, §3). Every report
-- becomes an entry. A reading becomes the second child of its report's entry when both were
-- written by one `log_smell` call, recognised in the audit log: the reading's `create` entry is
-- the one right after the report's (audit id + 1), by the same actor, with the same
-- `observed_at` in the two `create` snapshots. The current event, time and `recorded_at` are not
-- compared: the report may have been moved or retimed since. The shared entry takes the
-- report's current values. Any other reading gets its own entry, without a note.
-- Report and reading ids are kept. The audit log is not touched.
-- Kept in step with crates/storage-sqlite/migrations; tests/schema_parity.rs compares the
-- columns, and scripts/neon-preflight-0005.sql runs the same pairing rule read-only.

CREATE TEMP TABLE pairs (
    report_id  BIGINT NOT NULL PRIMARY KEY,
    reading_id BIGINT NOT NULL UNIQUE
);

INSERT INTO pairs (report_id, reading_id)
SELECT ar.entity_id, ap.entity_id
FROM audit_log ar
JOIN audit_log ap
  ON ap.id = ar.id + 1
 AND ap.entity = 'pm25_reading' AND ap.action = 'create'
 AND ap.actor_id IS NOT DISTINCT FROM ar.actor_id
 AND (ap.after_json::jsonb -> 'observed_at') = (ar.after_json::jsonb -> 'observed_at')
WHERE ar.entity = 'smell_report' AND ar.action = 'create';

-- Without a `create` entry a row cannot be paired: the migration refuses to run while one
-- exists, instead of guessing.
DO $$
BEGIN
    IF EXISTS (
        SELECT 1 FROM smell_reports r
        WHERE NOT EXISTS (SELECT 1 FROM audit_log a WHERE a.entity = 'smell_report'
                          AND a.entity_id = r.id AND a.action = 'create')
    ) OR EXISTS (
        SELECT 1 FROM pm25_readings p
        WHERE NOT EXISTS (SELECT 1 FROM audit_log a WHERE a.entity = 'pm25_reading'
                          AND a.entity_id = p.id AND a.action = 'create')
    ) THEN
        RAISE EXCEPTION 'every_report_and_reading_has_a_create_entry: a report or reading has no create entry in the audit log';
    END IF;
END
$$;

CREATE TABLE log_entries (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      BIGINT NOT NULL REFERENCES users (id),
    event_id     BIGINT REFERENCES events (id),
    observed_at  BIGINT NOT NULL,
    recorded_at  BIGINT NOT NULL,
    note         TEXT,
    deleted_at   BIGINT,
    from_report  BIGINT,
    from_reading BIGINT
);

INSERT INTO log_entries (user_id, event_id, observed_at, recorded_at, note, deleted_at, from_report)
SELECT user_id, event_id, observed_at, recorded_at, note, deleted_at, id
FROM smell_reports ORDER BY id;

INSERT INTO log_entries (user_id, event_id, observed_at, recorded_at, note, deleted_at, from_reading)
SELECT user_id, event_id, observed_at, recorded_at, NULL, deleted_at, id
FROM pm25_readings
WHERE id NOT IN (SELECT reading_id FROM pairs)
ORDER BY id;

ALTER TABLE smell_reports ADD COLUMN log_entry_id BIGINT;
UPDATE smell_reports r SET log_entry_id = e.id FROM log_entries e WHERE e.from_report = r.id;

ALTER TABLE pm25_readings ADD COLUMN log_entry_id BIGINT;
UPDATE pm25_readings p SET log_entry_id = e.id FROM log_entries e WHERE e.from_reading = p.id;
-- A paired reading takes its report's entry.
UPDATE pm25_readings p SET log_entry_id = e.id
FROM pairs, log_entries e
WHERE pairs.reading_id = p.id AND e.from_report = pairs.report_id;

ALTER TABLE smell_reports
    ALTER COLUMN log_entry_id SET NOT NULL,
    ADD CONSTRAINT smell_reports_log_entry_id_key UNIQUE (log_entry_id),
    ADD CONSTRAINT smell_reports_log_entry_id_fkey FOREIGN KEY (log_entry_id) REFERENCES log_entries (id);

ALTER TABLE pm25_readings
    ALTER COLUMN log_entry_id SET NOT NULL,
    ADD CONSTRAINT pm25_readings_log_entry_id_key UNIQUE (log_entry_id),
    ADD CONSTRAINT pm25_readings_log_entry_id_fkey FOREIGN KEY (log_entry_id) REFERENCES log_entries (id);

DROP INDEX smell_reports_event;
DROP INDEX pm25_readings_event;

ALTER TABLE smell_reports
    DROP COLUMN user_id,
    DROP COLUMN event_id,
    DROP COLUMN observed_at,
    DROP COLUMN recorded_at,
    DROP COLUMN note,
    DROP COLUMN deleted_at;

ALTER TABLE pm25_readings
    DROP COLUMN user_id,
    DROP COLUMN event_id,
    DROP COLUMN observed_at,
    DROP COLUMN recorded_at,
    DROP COLUMN deleted_at;

ALTER TABLE log_entries
    DROP COLUMN from_report,
    DROP COLUMN from_reading;

CREATE INDEX log_entries_event ON log_entries (event_id, observed_at);

DROP TABLE pairs;
